import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "reference/Fuse.svg";
const OUTPUT = "ui/src/diagram/fuseArt.generated.ts";
const TARGET_PITCH = 96; // local units, same columns as NCTO
const PROJECTION_SCALE = 1.25;
const PROJECTION_Y = 11;
const CENTER_X = 64;
const CENTER_Y = 30;
const TARGET_LINE = 4.38;

const raw = readFileSync(SOURCE, "utf8");
const elements = [...raw.matchAll(/<(path|rect)\b[^>]*\/>/g)].map((match, index) => {
  const attrs = {};
  for (const attr of match[0].matchAll(/([a-zA-Z0-9-]+)="([^"]*)"/g)) {
    if (attr[1] && attr[2] !== undefined) attrs[attr[1]] = attr[2];
  }
  return { index, tag: match[1], attrs };
});

if (elements.length !== 2 || elements[0].tag !== "path" || elements[1].tag !== "rect") {
  throw new Error(`Unexpected Fuse.svg structure: ${elements.map((element) => element.tag).join(",")}`);
}

function pathPoints(d) {
  const numbers = [...d.matchAll(/[-+]?(?:(?:\d+\.?\d*)|(?:\.\d+))(?:[eE][-+]?\d+)?/g)].map((match) => Number(match[0]));
  const points = [];
  for (let index = 0; index + 1 < numbers.length; index += 2) {
    points.push({ x: numbers[index], y: numbers[index + 1] });
  }
  return points;
}

function boundsOfElement(element) {
  if (element.tag === "rect") {
    const x = Number(element.attrs.x);
    const y = Number(element.attrs.y);
    const width = Number(element.attrs.width);
    const height = Number(element.attrs.height);
    return { bottom: y + height, left: x, right: x + width, top: y };
  }
  const points = pathPoints(element.attrs.d);
  return {
    bottom: Math.max(...points.map((point) => point.y)),
    left: Math.min(...points.map((point) => point.x)),
    right: Math.max(...points.map((point) => point.x)),
    top: Math.min(...points.map((point) => point.y))
  };
}

const bodyBounds = boundsOfElement(elements[0]);
const rectBounds = boundsOfElement(elements[1]);
const sourceBounds = {
  bottom: Math.max(bodyBounds.bottom, rectBounds.bottom),
  left: Math.min(bodyBounds.left, rectBounds.left),
  right: Math.max(bodyBounds.right, rectBounds.right),
  top: Math.min(bodyBounds.top, rectBounds.top)
};

// Lead ends: the rect's left edge and the body's right edge.
const leftAnchor = { x: rectBounds.left, y: (rectBounds.top + rectBounds.bottom) / 2 };
const rightAnchor = { x: bodyBounds.right, y: (rectBounds.top + rectBounds.bottom) / 2 };
const scale = (TARGET_PITCH / PROJECTION_SCALE) / (rightAnchor.x - leftAnchor.x);
const translateX = CENTER_X - ((leftAnchor.x + rightAnchor.x) / 2) * scale;
const translateY = CENTER_Y - ((leftAnchor.y + rightAnchor.y) / 2) * scale;
const transform = `translate(${translateX.toFixed(8)} ${translateY.toFixed(8)}) scale(${scale.toFixed(8)})`;

// The fuse art is filled; add a same-colour outline so the rendered line reaches
// the NCTO weight. Source and rendered local thickness are both printed below.
const sourceLine = 3.977; // rect height / stroke-equivalent line in the SVG
const intrinsicLocalLine = sourceLine * scale * PROJECTION_SCALE;
const strokeWidth = (TARGET_LINE - intrinsicLocalLine) / (scale * PROJECTION_SCALE);
const strokeHalf = strokeWidth / 2;

function project(bounds) {
  return {
    bottom: (bounds.bottom * scale + translateY) * PROJECTION_SCALE + PROJECTION_Y,
    left: (bounds.left * scale + translateX) * PROJECTION_SCALE,
    right: (bounds.right * scale + translateX) * PROJECTION_SCALE,
    top: (bounds.top * scale + translateY) * PROJECTION_SCALE + PROJECTION_Y
  };
}

const projected = project({
  bottom: sourceBounds.bottom + strokeHalf,
  left: sourceBounds.left - strokeHalf,
  right: sourceBounds.right + strokeHalf,
  top: sourceBounds.top - strokeHalf
});

const hash = (value) => createHash("sha256").update(value).digest("hex");
const module = `/* This file is generated by scripts/generate-fuse-art.mjs. */
/* Source: ${SOURCE}; original path/rect order preserved. */

export interface FuseGeneratedElement {
  tag: "path" | "rect";
  d?: string;
  x?: number;
  y?: number;
  width?: number;
  height?: number;
}

export interface FuseArt {
  anchors: readonly [{ x: number; y: number }, { x: number; y: number }];
  elements: readonly FuseGeneratedElement[];
  strokeWidth: number;
  tightBounds: { bottom: number; left: number; right: number; top: number };
  transform: string;
}

export const FUSE_ART: FuseArt = {
  transform: ${JSON.stringify(transform)},
  strokeWidth: ${strokeWidth},
  anchors: [
    { x: 32, y: 48.5 },
    { x: 128, y: 48.5 },
  ],
  tightBounds: ${JSON.stringify(projected)},
  elements: [
${elements.map((element) => element.tag === "path"
  ? `    { tag: "path", d: ${JSON.stringify(element.attrs.d)} },`
  : `    { tag: "rect", x: ${Number(element.attrs.x)}, y: ${Number(element.attrs.y)}, width: ${Number(element.attrs.width)}, height: ${Number(element.attrs.height)} },`).join("\n")}
  ]
};
`;
writeFileSync(OUTPUT, module);

console.log(`source elements=${elements.length}; generated=${elements.length}`);
for (const element of elements) {
  const serialized = element.tag === "path" ? element.attrs.d : JSON.stringify(element.attrs);
  console.log(`${element.tag}: ${hash(serialized)} ${serialized.length}`);
}
console.log(`transform=${transform}`);
console.log(`anchors=${JSON.stringify([{ x: 32, y: 48.5 }, { x: 128, y: 48.5 }])}`);
console.log(`tightBounds=${JSON.stringify(projected)}`);
console.log(`intrinsicLocalLine=${intrinsicLocalLine.toFixed(4)} strokeWidth=${strokeWidth.toFixed(4)} renderedLine=${(intrinsicLocalLine + strokeWidth * scale * PROJECTION_SCALE).toFixed(4)}`);
